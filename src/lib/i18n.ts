export function isLocaleId(value: string | undefined | null): value is LocaleId {
  return Boolean(value && (LOCALE_IDS as readonly string[]).includes(value));
}

export function matchLocale(tag: string | undefined | null): LocaleId {
  const raw = (tag ?? "").trim().toLowerCase().replace(/_/g, "-");
  if (!raw) return "en";
  if (raw.startsWith("ps")) return "ps";
  if (raw.startsWith("prs") || raw === "fa-af" || raw.startsWith("fa-af") || raw.includes("dari")) {
    return "prs";
  }
  if (raw.startsWith("fa")) return "fa";
  if (raw.startsWith("ar")) return "ar";
  if (raw.startsWith("zh")) return "zh";
  if (raw.startsWith("ja")) return "ja";
  if (raw.startsWith("hi")) return "hi";
  if (raw.startsWith("pt")) return "pt";
  if (raw.startsWith("ru")) return "ru";
  if (raw.startsWith("nl")) return "nl";
  if (raw.startsWith("de")) return "de";
  if (raw.startsWith("es")) return "es";
  if (raw.startsWith("it")) return "it";
  if (raw.startsWith("en")) return "en";
  return "en";
}

export function detectLocale(): LocaleId {
  if (typeof navigator === "undefined") return "en";
  const langs = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const tag of langs) {
    const hit = matchLocale(tag);
    if (hit !== "en" || String(tag).toLowerCase().startsWith("en")) return hit;
  }
  return matchLocale(navigator.language);
}

export function localeInfo(id: string | undefined | null): LocaleInfo {
  const loc = isLocaleId(id) ? id : matchLocale(id);
  return LOCALES.find((l) => l.id === loc) ?? LOCALES[0]!;
}

export function t(locale: string | undefined | null, key: MsgKey, vars?: Record<string, string>) {
  const id = isLocaleId(locale) ? locale : matchLocale(locale);
  let s = DICT[id][key] ?? EN[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  }
  return s;
}

export function applyLocale(id: string | undefined | null) {
  if (typeof document === "undefined") return;
  const info = localeInfo(id);
  const root = document.documentElement;
  root.lang = info.htmlLang;
  root.dir = info.dir;
}

export function greetingKey(date = new Date()): MsgKey {
  const h = date.getHours();
  if (h < 5) return "greetingLate";
  if (h < 12) return "greetingMorning";
  if (h < 18) return "greetingAfternoon";
  return "greetingEvening";
}

